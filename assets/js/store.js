async function seedIfEmpty(){
  const seedRef = doc(db, "config", "seeded");
  const seedSnap = await getDoc(seedRef);
  if(seedSnap.exists()) return;

  const batch = writeBatch(db);

  DEFAULT_PAGES.forEach(page=>{
    batch.set(doc(db, "pages", page.slug), page);
  });

  batch.set(doc(db, "config", "menu"), {items: DEFAULT_MENU});
  batch.set(doc(db, "config", "settings"), DEFAULT_SETTINGS);

  SAMPLE_POSTS.forEach((p, i)=>{
    const postRef = doc(collection(db, "posts"));
    batch.set(postRef, {
      ...p,
      status: "published",
      date: new Date(Date.now() - i*43200000).toISOString(),
      author: "রঙিন দুনিয়া টিম",
      cover: "",
      likes: 0
    });
  });

  batch.set(seedRef, {done:true, date:new Date().toISOString()});
  await batch.commit();
}

let _seedPromise = null;
function ensureSeeded(){
  if(!_seedPromise) _seedPromise = seedIfEmpty();
  return _seedPromise;
}

const Store = {
  // ---------- Pages ----------
  async getPages(){
    await ensureSeeded();
    const snap = await getDocs(collection(db, "pages"));
    return snap.docs.map(d=>d.data());
  },
  async savePage(page){
    await ensureSeeded();
    await setDoc(doc(db, "pages", page.slug), page);
    return page;
  },
  async deletePage(slug){
    await deleteDoc(doc(db, "pages", slug));
  },

  // ---------- Posts ----------
  async getPosts(category){
    await ensureSeeded();
    let snap;
    if(category){
      snap = await getDocs(query(collection(db, "posts"), where("category","==",category)));
    } else {
      snap = await getDocs(collection(db, "posts"));
    }
    const posts = snap.docs.map(d=>({id:d.id, ...d.data()}));
    posts.sort((a,b)=> new Date(b.date) - new Date(a.date));
    return posts;
  },
  async getPost(id){
    const snap = await getDoc(doc(db, "posts", id));
    return snap.exists() ? {id:snap.id, ...snap.data()} : null;
  },
  async savePost(post){
    if(post.id){
      const {id, ...rest} = post;
      await updateDoc(doc(db, "posts", id), rest);
      return post;
    } else {
      const newPost = {...post, date:new Date().toISOString(), likes:0};
      const docRef = await addDoc(collection(db, "posts"), newPost);
      return {id:docRef.id, ...newPost};
    }
  },
  async deletePost(id){
    await deleteDoc(doc(db, "posts", id));
  },

  // ---------- Menu ----------
  async getMenu(){
    await ensureSeeded();
    const snap = await getDoc(doc(db, "config", "menu"));
    return snap.exists() ? snap.data().items : DEFAULT_MENU;
  },
  async saveMenu(menu){
    await setDoc(doc(db, "config", "menu"), {items: menu});
  },

  // ---------- Comments ----------
  async getComments(postId){
    const snap = await getDocs(query(collection(db, "comments"), where("postId","==",postId)));
    const list = snap.docs.map(d=>({id:d.id, ...d.data()}));
    list.sort((a,b)=> new Date(b.date) - new Date(a.date));
    return list;
  },
  async addComment(postId, comment){
    const entry = {postId, name: comment.name, text: comment.text, date: new Date().toISOString()};
    const docRef = await addDoc(collection(db, "comments"), entry);
    return {id:docRef.id, ...entry};
  },
  async deleteComment(postId, commentId){
    await deleteDoc(doc(db, "comments", commentId));
  },
  async getAllComments(){
    const snap = await getDocs(collection(db, "comments"));
    const list = snap.docs.map(d=>({id:d.id, ...d.data()}));
    list.sort((a,b)=> new Date(b.date) - new Date(a.date));
    return list;
  },

  // ---------- Likes (count in Firestore, "কে লাইক দিয়েছে" শুধু এই ব্রাউজারে) ----------
  async toggleLike(postId){
    const mineKey = "rd_liked_by_me";
    const mine = _readLocal(mineKey, {});
    const postRef = doc(db, "posts", postId);
    const snap = await getDoc(postRef);
    const current = snap.exists() ? (snap.data().likes || 0) : 0;

    let newCount, liked;
    if(mine[postId]){
      newCount = Math.max(0, current - 1);
      delete mine[postId];
      liked = false;
    } else {
      newCount = current + 1;
      mine[postId] = true;
      liked = true;
    }
    await updateDoc(postRef, {likes: newCount});
    _writeLocal(mineKey, mine);
    return {count: newCount, liked};
  },
  async getLikeState(postId){
    const mine = _readLocal("rd_liked_by_me", {});
    const snap = await getDoc(doc(db, "posts", postId));
    const count = snap.exists() ? (snap.data().likes || 0) : 0;
    return {count, liked: !!mine[postId]};
  },

  // ---------- Media library (ছবি → compressed base64, ভিডিও/পিডিএফ → পেস্ট করা লিংক) ----------
  async getMedia(){
    const snap = await getDocs(collection(db, "media"));
    const list = snap.docs.map(d=>({id:d.id, ...d.data()}));
    list.sort((a,b)=> new Date(b.date) - new Date(a.date));
    return list;
  },
  // item: {type, name, src}  — src হলো base64 dataURL (ছবি) অথবা একটা লিংক (ভিডিও/পিডিএফ)
  async addMedia(item){
    if(item.src && item.src.length > 900000){
      throw new Error("ছবিটি এখনো অনেক বড়, আরেকটু ছোট ছবি ব্যবহার করো (Firestore এ প্রতিটি নথি সর্বোচ্চ ~1MB)");
    }
    const entry = {type:item.type, name:item.name, src:item.src, date:new Date().toISOString()};
    const docRef = await addDoc(collection(db, "media"), entry);
    return {id:docRef.id, ...entry};
  },
  async deleteMedia(id){
    await deleteDoc(doc(db, "media", id));
  },

  // ---------- Settings ----------
  async getSettings(){
    await ensureSeeded();
    const snap = await getDoc(doc(db, "config", "settings"));
    return snap.exists() ? snap.data() : DEFAULT_SETTINGS;
  },
  async saveSettings(s){
    await setDoc(doc(db, "config", "settings"), s);
  }
};

window.Store = Store;
